"""scripts/go_coverage.py, which `make go-test` uses for the coverage floor: it
totals a real cover profile, leaves out generated files the way go.yml does, and
fails below the floor. Each case runs `go test` on a small module in a temporary
directory, so it needs Go, as `make test` does. Standard library only."""

from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "go_coverage.py"

TESTED = (
    "package fixture\n\n// Double is twice n.\nfunc Double(n int) int {\n\treturn n * 2\n}\n"
)
TESTED_TEST = (
    "package fixture\n\nimport \"testing\"\n\n"
    "func TestDouble(t *testing.T) {\n\tif Double(2) != 4 {\n\t\tt.Fatal(\"Double(2) != 4\")\n\t}\n}\n"
)
# Four untested statements beside the one tested above.
UNTESTED = (
    "package pb\n\n// Laps is the laps run.\nfunc Laps(stints []int) int {\n\tn := 0\n"
    "\tfor _, s := range stints {\n\t\tn += s\n\t}\n\treturn n\n}\n"
)
HEADER = "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: laps.proto\n\n"


class GoCoverage(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.module = Path(tmp.name)
        self.write("go.mod", "module example.com/fixture\n\ngo 1.27.0\n")
        self.write("fixture.go", TESTED)
        self.write("fixture_test.go", TESTED_TEST)

    def write(self, name: str, text: str) -> None:
        path = self.module / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def coverage(self, floor: str = "90") -> tuple[int, str]:
        profile = self.module / "cover.out"
        subprocess.run(
            ["go", "test", f"-coverprofile={profile}", "./..."],
            cwd=self.module,
            check=True,
            capture_output=True,
        )
        proc = subprocess.run(
            [sys.executable, str(SCRIPT), str(profile), floor],
            cwd=self.module,
            capture_output=True,
            text=True,
        )
        return proc.returncode, proc.stdout + proc.stderr

    def test_a_covered_module_passes(self):
        code, out = self.coverage()
        self.assertEqual(code, 0, out)
        self.assertIn("Coverage: 100.0% of statements (the floor is 90%).", out)

    def test_untested_code_fails_the_floor(self):
        self.write("pb/laps.go", UNTESTED)
        code, out = self.coverage()
        self.assertEqual(code, 1, out)
        self.assertIn("coverage is below the floor", out)
        code, out = self.coverage("20")
        self.assertEqual(code, 0, out)

    def test_generated_files_are_left_out(self):
        self.write("pb/laps.pb.go", HEADER + UNTESTED)
        code, out = self.coverage()
        self.assertEqual(code, 0, out)
        self.assertIn("Coverage: 100.0% of statements", out)
        self.assertIn("leaves out 1 generated file(s): pb/laps.pb.go", out)

    def test_only_gos_exact_line_before_the_package_clause_counts(self):
        self.write("pb/laps.pb.go", "// Code generated by hand, edit freely.\n\n" + UNTESTED)
        self.assertEqual(self.coverage()[0], 1)
        self.write("pb/laps.pb.go", UNTESTED + "\n// Code generated by protoc-gen-go. DO NOT EDIT.\n")
        self.assertEqual(self.coverage()[0], 1)
        # A block comment before the clause, on its line, doesn't move the end of
        # the search past it, as go/ast's IsGenerated has it.
        clause_after = UNTESTED.replace("package pb\n", "/* hand-written */ package pb\n\n" + HEADER, 1)
        self.write("pb/laps.pb.go", clause_after)
        self.assertEqual(self.coverage()[0], 1)
        self.write("pb/laps.pb.go", "/*\nhand-written\n*/ " + clause_after.replace("/* hand-written */ ", ""))
        self.assertEqual(self.coverage()[0], 1)

    def test_a_licence_block_before_the_line_does_not_hide_it(self):
        self.write("pb/laps.pb.go", "/*\nCopyright the authors.\n*/\n\n" + HEADER + UNTESTED)
        code, out = self.coverage()
        self.assertEqual(code, 0, out)
        self.assertIn("leaves out 1 generated file(s): pb/laps.pb.go", out)

    def test_a_module_of_generated_code_alone_skips_the_floor(self):
        # Every statement generated, as contracts is before it has helpers: nothing
        # is left to measure, which is not 0% coverage.
        self.write("fixture.go", HEADER + TESTED)
        code, out = self.coverage()
        self.assertEqual(code, 0, out)
        self.assertIn("leaves out 1 generated file(s): fixture.go", out)
        self.assertIn("no statements are left once generated files are left out", out)
        self.assertNotIn("Coverage: 0.0%", out)


if __name__ == "__main__":
    unittest.main()
